"""Generate the D8/D17 floor tests (vitest) for one village + rev.

The tests run inside the Daytona sandbox against the bundle (src/village/{spec,theme}.json
plus the catalog renderer). They import the same `styleFor()` the components use, so a
token that renders 4.1:1 fails here exactly as it would on the elder's phone.
"""
from __future__ import annotations

import json
from typing import Any

# D8 floor constants (locked; the village layer cannot change them).
FLOOR = {
    "safety": {"stopped": "#A8331A", "recorded": "#2E6F42", "needs_person": "#7A4E00"},
    "paper": "#FBF6EE",
    "ink": "#1F1A15",
    "elder_actionable_px": 28,
    "elder_min_px": 22,
    "elder_button_px": 88,
    "elder_contrast": 7.0,
    "other_contrast": 4.5,
    "tap_px": 48,
    "max_elder_bigbuttons": 3,
}

ELDER_THEME = "elder"

_TEMPLATE = r"""// GENERATED by core/release/floor_tests.py for __VILLAGE__ rev __REV__. Do not edit.
import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { renderToStaticMarkup } from "react-dom/server";
import spec from "../../src/village/spec.json";
import theme from "../../src/village/theme.json";
import { isCatalogType, secondaryPx, styleFor, type ThemeName } from "../../src/catalog";
import { renderView, type View } from "../../src/render";

const FLOOR = __FLOOR__;
const views = (spec as unknown as { views: Record<string, View> }).views;

function lum(hex: string): number {
  const h = hex.replace("#", "");
  const c = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
    .map((x) => (x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}
export function contrast(a: string, b: string): number {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}
const fmt = (r: number) => (Math.floor(r * 10) / 10).toFixed(1);

describe("floor/contrast", () => {
  for (const [role, view] of Object.entries(views)) {
    const need = view.theme === "elder" ? FLOOR.elder_contrast : FLOOR.other_contrast;
    for (const [id, el] of Object.entries(view.elements)) {
      if (!isCatalogType(el.type)) continue;
      const s = styleFor(el.type, el.props, view.theme as ThemeName);
      const label = `${role} ${el.type}${el.props.tone ? " tone=" + el.props.tone : ""} #${id}`;
      it(`${label} contrast >= ${need}:1`, () => {
        const r = contrast(s.color, s.background);
        expect(r >= need, `contrast ${fmt(r)}:1 on ${view.theme === "elder" ? "elder" : role} Text (${label}) < ${need}:1`).toBe(true);
      });
    }
  }
});

describe("floor/sizes", () => {
  for (const [role, view] of Object.entries(views)) {
    if (view.theme !== "elder") continue;
    it(`${role} secondary text >= ${FLOOR.elder_min_px}px`, () => {
      expect(secondaryPx("elder")).toBeGreaterThanOrEqual(FLOOR.elder_min_px);
    });
    for (const [id, el] of Object.entries(view.elements)) {
      if (!isCatalogType(el.type)) continue;
      const s = styleFor(el.type, el.props, "elder");
      it(`${role} ${el.type} #${id} text >= ${s.role === "actionable" || s.role === "headline" ? FLOOR.elder_actionable_px : FLOOR.elder_min_px}px`, () => {
        expect(s.fontSize, `font ${s.fontSize}px on elder ${el.type} #${id}`).toBeGreaterThanOrEqual(FLOOR.elder_min_px);
        if (s.role === "actionable" || s.role === "headline") expect(s.fontSize).toBeGreaterThanOrEqual(FLOOR.elder_actionable_px);
      });
      if (el.type === "BigButton" || el.type === "ContactCard") {
        it(`${role} ${el.type} #${id} height >= ${FLOOR.elder_button_px}px`, () => {
          expect(s.minHeight, `button ${s.minHeight}px on elder #${id}`).toBeGreaterThanOrEqual(FLOOR.elder_button_px);
        });
      }
    }
  }
  for (const [role, view] of Object.entries(views)) {
    if (view.theme === "elder") continue;
    it(`${role} tap targets >= ${FLOOR.tap_px}px`, () => {
      for (const el of Object.values(view.elements)) {
        if (el.type !== "BigButton") continue;
        expect(styleFor(el.type, el.props, view.theme as ThemeName).minHeight).toBeGreaterThanOrEqual(FLOOR.tap_px);
      }
    });
  }
});

describe("floor/safety_colors", () => {
  it("safety colors unchanged", () => {
    expect(theme.safety).toEqual(FLOOR.safety);
    expect(theme.tones.danger.bar).toBe(FLOOR.safety.stopped);
    expect(theme.tones.ok.bar).toBe(FLOOR.safety.recorded);
    expect(theme.floor.paper).toBe(FLOOR.paper);
    expect(theme.floor.ink).toBe(FLOOR.ink);
  });
});

describe("floor/catalog", () => {
  for (const [role, view] of Object.entries(views)) {
    it(`${role} uses catalog-only component types`, () => {
      const bad = Object.values(view.elements).map((e) => e.type).filter((t) => !isCatalogType(t));
      expect(bad).toEqual([]);
    });
    it(`${role} renders (unknown types render nothing)`, () => {
      const probe: View = { ...view, elements: { ...view.elements, zz_unknown: { type: "Iframe", props: { src: "x" } } } };
      (probe.elements[probe.root].children ?? []).push("zz_unknown");
      const html = renderToStaticMarkup(renderView(probe) as never);
      expect(html).toContain("data-type=\"Screen\"");
      expect(html).not.toContain("Iframe");
    });
  }
});

describe("floor/elder_view", () => {
  for (const [role, view] of Object.entries(views)) {
    if (view.theme !== "elder") continue;
    const els = Object.values(view.elements);
    it(`${role} has <= ${FLOOR.max_elder_bigbuttons} BigButtons`, () => {
      expect(els.filter((e) => e.type === "BigButton").length).toBeLessThanOrEqual(FLOOR.max_elder_bigbuttons);
    });
    it(`${role} has the 911 ContactCard`, () => {
      expect(els.some((e) => e.type === "ContactCard" && String(e.props.phone) === "911")).toBe(true);
    });
  }
});

describe("floor/no_network", () => {
  const dir = join(__dirname, "../../src");
  const files = readdirSync(dir, { recursive: true }).map(String).filter((f) => /\.(ts|tsx|js|jsx)$/.test(f));
  for (const f of files) {
    it(`${f} makes no raw network calls`, () => {
      const src = readFileSync(join(dir, f), "utf8");
      expect(src).not.toMatch(/\bfetch\s*\(|XMLHttpRequest|new\s+WebSocket|EventSource|sendBeacon|axios/);
    });
  }
});
"""


def render(village_id: str, rev: int, floor: dict[str, Any] | None = None) -> str:
    """Return the vitest source for this village/rev."""
    f = dict(FLOOR)
    if floor:
        f.update(floor)
    return (
        _TEMPLATE.replace("__VILLAGE__", village_id)
        .replace("__REV__", str(rev))
        .replace("__FLOOR__", json.dumps(f, indent=2))
    )


def files(village_id: str, rev: int) -> dict[str, str]:
    return {"tests/floor/floor.test.ts": render(village_id, rev)}
